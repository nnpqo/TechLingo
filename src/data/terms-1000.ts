const makeDefinition = (area: TechArea, base: Base, suffixEn: string) => {
  const areaNameEs: Record<TechArea, string> = {
    cybersecurity: 'ciberseguridad',
    frontend: 'frontend',
    backend: 'backend',
    database: 'bases de datos',
    devops: 'DevOps',
    networking: 'redes',
  };

  return {
    definition_en: `In ${area}, “${base.english} ${suffixEn}” describes a topic or technique related to ${base.english}. It focuses on how teams apply it in real systems (design, implementation, and operations).`,
    definition_es: `En ${areaNameEs[area]}, “${base.english} ${suffixEn}” describe un tema o técnica relacionada con ${base.spanish}. Se enfoca en cómo se aplica en sistemas reales (diseño, implementación y operación).`,
  };
};

const uniqueByKey = <T,>(items: T[], keyFn: (item: T) => string) => {
  const seen = new Set<string>();
  const out: T[] = [];
  for (const item of items) {
    const key = keyFn(item);
    if (seen.has(key)) continue;
    seen.add(key);
    out.push(item);
  }
  return out;
};

const toTerm = (base: Base, id: string): Term => {
  return {
    id,
    english: base.english,
    spanish: base.spanish,
    phonetic: base.phonetic || '',
    pronunciation_guide: base.pronunciation_guide || base.english,
    definition_en: base.definition_en,
    definition_es: base.definition_es,
    area: base.area,
    level: base.level,
    codeExample: undefined,
    contextSentence: `Example usage of ${base.english} in ${base.area}.`,
    tags: [base.area, base.level, ...(base.tags || [])],
    relatedTerms: [],
  };
};

const buildAreaTerms = (area: TechArea, target: number): Term[] => {
  const bases = baseTerms.filter((t) => t.area === area);

  const results: Base[] = [...bases];
  const suffixes = derivedSuffixesByArea[area];

  for (const base of bases) {
    for (const s of suffixes) {
      const english = `${base.english} ${s.en}`;
      const spanish = `${base.spanish} ${s.es}`;
      const defs = makeDefinition(area, base, s.en);
      results.push({
        ...base,
        english,
        spanish,
        level: s.level,
        phonetic: base.phonetic || '',
        pronunciation_guide: base.pronunciation_guide || base.english,
        ...defs,
        tags: [...(base.tags || []), s.en],
      });
    }
  }

  const uniq = uniqueByKey(results, (t) => `${t.english.toLowerCase()}|${t.area}`);
  const sliced = uniq.slice(0, target);

  return sliced.map((b, idx) => toTerm(b, `${area}_${String(idx + 1).padStart(4, '0')}`));
};

